"""Generate the Feature Support tables from the checked-in support records."""
import argparse
from collections import Counter
import importlib.util
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parent.parent


def load_refusals():
  # Read the source table, even when the staged package predates it.
  spec = importlib.util.spec_from_file_location(
      'support_refusals', ROOT / 'src/python/backends/refusals.py')
  module = importlib.util.module_from_spec(spec)
  spec.loader.exec_module(module)
  return module


def issue_links(text):
  return re.sub(r'#(\d+)', lambda match:
      '`#%s <https://github.com/andyjost/Sprite/issues/%s>`_' %
      (match[1], match[1]), text)


def list_table(headers, rows):
  lines = ['.. list-table::', '   :header-rows: 1', '']
  for row in [headers, *rows]:
    for column, cell in enumerate(row):
      lines.append((('   * - ' if column == 0 else '     - ') + cell).rstrip())
  return '\n'.join(lines) + '\n'


def render(expected, refusals):
  packages = expected['packages']
  counts = Counter(pin['result'] for pin in packages.values())
  lines = [
      '.. Generated by docs/build-feature-support.py. Do not edit.', '',
      '.. begin-counts', '',
      '.. |cpm-pass-count| replace:: %d' % counts['pass'],
      '.. |cpm-exception-count| replace:: %d' % counts['exception'],
      '.. |cpm-open-count| replace:: %d' % counts['open'],
      '.. |cpm-tested-count| replace:: %d' % len(packages),
      '.. |cpm-index-count| replace:: %d' % len(expected['index']['versions']),
      '.. |cpm-index-date| replace:: %s' % expected['index']['date'],
      '.. |cpm-index-sha256| replace:: ``%s``' % expected['index']['sha256'],
      '', '.. end-counts', '', '.. begin-packages', '',
  ]
  rows = []
  for name, pin in sorted(packages.items()):
    result = pin['result']
    reason = pin.get('reason', '')
    category = ''
    if result == 'exception':
      match = re.fullmatch(r'Class ([1-5]): (.+)', reason)
      if match is None:
        raise ValueError('Missing exception class: ' + name)
      category = 'Class ' + match[1]
      reason = re.split(r'\.\s+', match[2], maxsplit=1)[0].rstrip('.') + '.'
      if pin.get('issue'):
        reason += ' ' + pin['issue']
    elif result == 'open':
      # Keep the full record: it distinguishes current issues from closed ones.
      reason = pin.get('issue', '') + ': ' + reason
    elif result != 'pass':
      raise ValueError('Unknown package result: ' + result)
    rows.append(('``%s``' % name, pin['version'],
                 'known exception' if result == 'exception' else result,
                 category, issue_links(reason)))
  lines.append(list_table(('Package', 'Version', 'Result', 'Class', 'Reason / issues'), rows))
  lines.extend([
      '.. end-packages', '', '.. begin-refusals', '',
      'This list comes from :download:`refusals.py '
      '<../../src/python/backends/refusals.py>`.',
      'It applies to missing externals after registered primitive lookup.',
      'A module entry covers its missing externals.',
      'A named operation entry covers only that operation.', '',
  ])
  classes = {refusals.STRONG: 1, refusals.GLOBAL: 1, refusals.SOLVER: 4}
  rows = []
  for module, entry in refusals.REFUSED_EXTERNALS.items():
    entries = entry.items() if isinstance(entry, dict) else [('*', entry)]
    for operation, refusal in entries:
      rows.append(('Class %d' % classes[refusal], '``%s``' % module,
                   'all missing externals' if operation == '*' else '``%s``' % operation,
                   '%s; %s.' % (refusal.kind, refusal.sentence)))
  lines.append(list_table(('Class', 'Module', 'Scope', 'Reason'), sorted(rows)))
  lines.extend(['.. end-refusals', ''])
  return '\n'.join(lines)


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('output', type=Path)
  args = parser.parse_args()
  expected = json.loads((ROOT / 'tests/data/cpm/index-expected.json').read_text())
  args.output.write_text(render(expected, load_refusals()), encoding='ascii')


if __name__ == '__main__':
  main()
